def main():
    """main function to compute the reduced semver lag of DepUpdater(Lagease)
    /Dependabot/Snyk on the dataset of RQ1"""
    major_lag = 0
    minor_lag = 0
    patch_lag = 0
    modules = dataset()
    # result of DepUpdater(Lagease)
    # Reduced Major lag: 1219, Reduced Minor lag: 4766, Reduced Patch lag: 18965 in RQ1
    base_path = f"/home1/kaixuan/ray/com_tool/data/Lagease_result"
    # result of Dependabot
    # base_path = f"/home1/kaixuan/ray/com_tool/data/dependabot"
    # resuot of Snyk
    # base_path = f"/home1/kaixuan/ray/com_tool/data/snyk"
    for module in modules:
        json_path = os.path.join(base_path, module[0], module[1], 'version.json')
        if not os.path.exists(json_path):
            # print("no")
            continue
        reduced_semver_lag = compute_reduced_semver_lag(json_path)
        major_lag += reduced_semver_lag[0]
        minor_lag += reduced_semver_lag[1]
        patch_lag += reduced_semver_lag[2]

    print(f"DepUpdater Reduced Major lag: {major_lag}, Reduced Minor lag: {minor_lag}, Reduced Patch lag: {patch_lag}")

